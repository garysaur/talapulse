import { Radio } from "lucide-react";

const PARAMS = [
  { key: "heart_rate", label: "Heart rate", unit: "bpm", digits: 0 },
  { key: "oxygen_percent", label: "Oxygen (SpO₂)", unit: "%", digits: 1 },
  { key: "co2_mmhg", label: "End-tidal CO₂", unit: "mmHg", digits: 1 },
  { key: "respiration_rate", label: "Respiration", unit: "br/min", digits: 1 },
  { key: "airflow_lpm", label: "Airflow", unit: "L/min", digits: 1 },
  { key: "skin_temp_c", label: "Temperature", unit: "°C", digits: 1 },
  { key: "gas_pressure_kpa", label: "Gas pressure", unit: "kPa", digits: 1 },
];

export default function SensorSnapshot({ sample, footer }) {
  return (
    <div className="space-y-3">
      <div className="flex items-center justify-between gap-2">
        <span className="chip" data-state="simulated">
          <Radio className="h-2.5 w-2.5" strokeWidth={2} />
          Simulated · PUMA-inspired
        </span>
        <span className="mono-label text-[8.5px]">{sample ? sample.label : "No sample"}</span>
      </div>
      {sample ? (
        <div className="grid grid-cols-2 gap-x-4 gap-y-2 sm:grid-cols-3">
          {PARAMS.map((param) => {
            const value = sample.values?.[param.key];
            return (
              <div key={param.key} className="border-b border-border/40 pb-1.5 last:border-0">
                <p className="mono-label text-[8.5px] leading-tight">{param.label}</p>
                <p className="mt-0.5 font-mono text-[13px] tabular text-foreground">
                  {value == null ? "—" : Number(value).toFixed(param.digits)}
                  <span className="ml-1 text-[9px] text-muted-foreground">{param.unit}</span>
                </p>
              </div>
            );
          })}
        </div>
      ) : (
        <p className="font-mono text-[11px] leading-relaxed text-muted-foreground">
          Run the sensor simulation to generate clearly labelled synthetic measurements.
        </p>
      )}
      <p className="font-mono text-[9.5px] leading-relaxed text-muted-foreground">
        {footer || "Synthetic values generated by this prototype. No PUMA device is connected and no NASA instrument data is used."}
      </p>
    </div>
  );
}
